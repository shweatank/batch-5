// ---------------- TEXT DRAW ----------------

void lcd_drawChar(int x, int y, char c, uint16_t color, uint16_t bg)
{
    if(c < 32 || c > 127) return;

    int scale = 3;
    int w = 5 * scale;
    int h = 7 * scale;

    // Set window for THIS character only
    writeReg(0x0036, x + w - 1);
    writeReg(0x0037, x);
    writeReg(0x0038, y + h - 1);
    writeReg(0x0039, y);

    // Reset GRAM address
    writeReg(0x0020, x);
    writeReg(0x0021, y);

    writeCmd(0x0022);
    digitalWrite(DC_PIN, HIGH);

    for(int row = 0; row < 7; row++)
    {
        for(int sy = 0; sy < scale; sy++)
        {
            for(int col = 0; col < 5; col++)
            {
                uint16_t pixel =
                    (font5x7[c-32][col] & (1<<row)) ? color : bg;

                for(int sx = 0; sx < scale; sx++)
                {
                    write16(pixel);
                }
            }
        }
    }
}

void lcd_drawString(int x, int y, char *str, uint16_t color, uint16_t bg)
{
    int scale = 3;

    while(*str)
    {
        lcd_drawChar(x, y, *str, color, bg);
        x += (5 * scale) + 2;
        str++;
    }
}

// ---------------- MAIN ----------------

int main()
{
    char text[100];

    wiringPiSetupGpio();
    pinMode(DC_PIN, OUTPUT);
    pinMode(RST_PIN, OUTPUT);

    if (wiringPiSPISetup(SPI_CHANNEL, SPI_SPEED) < 0)
    {
        printf("SPI Setup failed\n");
        return 1;
    }

    lcd_init();
    lcd_fill(0xFFFF);

    while(1) {
	printf("Enter text: ");
    	fgets(text,sizeof(text),stdin);
    	text[strcspn(text,"\n")] = 0;

    	lcd_drawString(10,50,text,0xF800,0xFFFF);
    }


    return 0;
}

